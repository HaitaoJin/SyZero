using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Linq;
using System.Text;

namespace SyZero.SourceGenerator;

/// <summary>
/// 为继承 <c>SyZeroServiceBase</c> 且实现 <c>IApplicationService</c> 的类型生成
/// 一段 marker 代码（占位骨架，未来用于生成 DI 注册或 controller 适配代码）。
/// 本版本仅作为「接入示例」，不影响业务运行。
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SyServiceMarkerGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var classes = context.SyntaxProvider.CreateSyntaxProvider(
            predicate: static (n, _) => n is ClassDeclarationSyntax c && c.BaseList != null,
            transform: static (ctx, _) => (ClassDeclarationSyntax)ctx.Node)
            .Where(static c => c.BaseList!.Types.Any(t => t.ToString().Contains("IApplicationService")));

        var collected = classes.Collect();

        context.RegisterSourceOutput(collected, static (spc, classNodes) =>
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("namespace SyZero.SourceGenerator.Generated");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>SyZero 自动收集到的 IApplicationService 列表（占位）。</summary>");
            sb.AppendLine("    internal static class SyDiscoveredServices");
            sb.AppendLine("    {");
            sb.Append("        public static readonly string[] Names = new string[] { ");
            sb.Append(string.Join(", ", classNodes.Select(c => "\"" + c.Identifier.Text + "\"")));
            sb.AppendLine(" };");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            spc.AddSource("SyDiscoveredServices.g.cs", sb.ToString());
        });
    }
}
