using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace SyZero.SourceGenerator;

/// <summary>
/// 扫描程序集中实现 <c>SyZero.Dependency.IScopedDependency</c> /
/// <c>ISingletonDependency</c> / <c>ITransientDependency</c> 的非抽象 class，
/// 生成 <c>SyZeroGeneratedRegistration.AddSyZeroGenerated(IServiceCollection)</c> 扩展方法，
/// 把每个候选类型按对应生命周期注册到 DI；如果该类型还实现了其他业务接口，会同时注册「接口 → 实现」的映射。
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SyDIRegistrationGenerator : IIncrementalGenerator
{
    private const string ScopedMarker = "SyZero.Dependency.IScopedDependency";
    private const string SingletonMarker = "SyZero.Dependency.ISingletonDependency";
    private const string TransientMarker = "SyZero.Dependency.ITransientDependency";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var classes = context.SyntaxProvider.CreateSyntaxProvider(
                predicate: static (n, _) => n is ClassDeclarationSyntax c && c.BaseList != null,
                transform: static (ctx, _) =>
                {
                    var symbol = ctx.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)ctx.Node) as INamedTypeSymbol;
                    return symbol;
                })
            .Where(static s => s is not null && !s.IsAbstract && s.TypeKind == TypeKind.Class)
            .Select(static (s, _) => s!);

        var collected = classes.Collect();
        var assemblyName = context.CompilationProvider.Select(static (c, _) => c.AssemblyName ?? "Assembly");

        context.RegisterSourceOutput(collected.Combine(assemblyName), static (spc, tuple) =>
        {
            var (symbols, asm) = tuple;
            var registrations = new List<(string Lifetime, INamedTypeSymbol Impl, IList<INamedTypeSymbol> Services)>();
            foreach (var sym in symbols)
            {
                var lifetime = ResolveLifetime(sym);
                if (lifetime == null) continue;

                var allInterfaces = sym.AllInterfaces;
                var businessInterfaces = allInterfaces
                    .Where(i => i.ToDisplayString() is not (ScopedMarker or SingletonMarker or TransientMarker))
                    // 排除间接实现的 marker 接口的 children（它们都是 IScoped/ISingleton/ITransient 的基类）
                    .Where(i => !i.AllInterfaces.Any(b => b.ToDisplayString() is ScopedMarker or SingletonMarker or TransientMarker)
                                && i.ToDisplayString() is not ScopedMarker and not SingletonMarker and not TransientMarker)
                    .ToList();
                registrations.Add((lifetime, sym, businessInterfaces));
            }

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("namespace SyZero.SourceGenerator.Generated");
            sb.AppendLine("{");
            sb.AppendLine($"    /// <summary>由 SyZero.SourceGenerator 为程序集 <c>{asm}</c> 生成。</summary>");
            sb.AppendLine("    internal static class SyZeroGeneratedRegistration");
            sb.AppendLine("    {");
            sb.AppendLine("        public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddSyZeroGenerated(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
            sb.AppendLine("        {");
            foreach (var (lifetime, impl, services) in registrations)
            {
                var implFqn = "global::" + impl.ToDisplayString();
                if (services.Count == 0)
                {
                    sb.AppendLine($"            services.Add{lifetime}<{implFqn}>();");
                }
                else
                {
                    sb.AppendLine($"            services.Add{lifetime}<{implFqn}>();");
                    foreach (var iface in services)
                    {
                        var ifaceFqn = "global::" + iface.ToDisplayString();
                        sb.AppendLine($"            services.Add{lifetime}<{ifaceFqn}>(sp => sp.GetRequiredService<{implFqn}>());");
                    }
                }
            }
            sb.AppendLine("            return services;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            spc.AddSource("SyZeroGeneratedRegistration.g.cs", sb.ToString());
        });
    }

    private static string? ResolveLifetime(INamedTypeSymbol symbol)
    {
        foreach (var iface in symbol.AllInterfaces)
        {
            switch (iface.ToDisplayString())
            {
                case ScopedMarker: return "Scoped";
                case SingletonMarker: return "Singleton";
                case TransientMarker: return "Transient";
            }
        }
        return null;
    }
}
